# find the largest number
num=[1,6,78,98,4,90,87]
print(max(num))


# find the smallest number
num=[1,6,78,98,4,90,87]
print(min(num))

# calculate the sum
num=[1,6,78,98,4,90,87]
print(sum(num))

# sort a list
num=[1,6,78,98,4,90,87]
num.sort()
print(num)

# sort in descending order
numbers = [40, 10, 30, 20]
numbers.sort(reverse=True)
